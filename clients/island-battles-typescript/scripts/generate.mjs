import { execFileSync } from "node:child_process";
import {
  mkdir,
  mkdtemp,
  readdir,
  readFile,
  rm,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const project = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const root = resolve(project, "../..");
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check"))
  throw new Error("Only --check is supported");
const temporary = await mkdtemp(join(tmpdir(), "island-ts-sdk-"));
try {
  const source = join(temporary, "openapi.json");
  const events = join(temporary, "events.json");
  execFileSync(
    "go",
    [
      "run",
      "./cmd/export-game-openapi",
      "--output",
      source,
      "--events-output",
      events,
    ],
    {
      cwd: root,
      stdio: "inherit",
      env: {
        ...process.env,
        GOCACHE: process.env.GOCACHE ?? "/tmp/island-game-go-cache",
      },
    },
  );
  for (const name of ["openapi.json", "events.json"]) {
    if (
      !(await readFile(join(temporary, name))).equals(
        await readFile(join(root, "api/game", name)),
      )
    ) {
      throw new Error(
        `api/game/${name} differs from the fresh Go export; regenerate the contract first`,
      );
    }
  }
  const spec = JSON.parse(await readFile(source, "utf8"));
  const operations = Object.values(spec.paths).flatMap((path) =>
    Object.values(path).map((operation) => operation.operationId),
  );
  for (const name of [
    "getIslandLobbyGeneration",
    "registerGenerationCommand",
    "createLobbyConnectionToken",
  ]) {
    if (!operations.includes(name))
      throw new Error(`Missing operation ${name}`);
  }
  for (const name of [
    "GenerationState",
    "GameNextGeneration",
    "ConnectionToken",
    "PublicGenerationCommand",
    "SendSoldierGroupParameters",
  ]) {
    if (!spec.components.schemas[name])
      throw new Error(`Missing schema ${name}`);
  }
  const types = astToString(
    await openapiTS(spec, { alphabetize: true, immutable: true }),
  );
  // The validators consume the exact component schemas, with local references.
  const schemas = JSON.parse(
    JSON.stringify(spec.components.schemas).replaceAll(
      "#/components/schemas/",
      "#/$defs/",
    ),
  );
  const artifacts = {
    "api.ts": `/** Generated by openapi-typescript. Run npm run generate; do not edit. */\n${types}`,
    "schemas.json": `${JSON.stringify(
      {
        $schema: "https://json-schema.org/draft/2020-12/schema",
        $defs: schemas,
      },
      null,
      2,
    )}\n`,
  };
  const destination = join(project, "src/generated");
  if (check) {
    const names = await readdir(destination);
    if (
      JSON.stringify(names.sort()) !==
      JSON.stringify(Object.keys(artifacts).sort())
    )
      throw new Error("Generated file set differs");
    for (const [name, contents] of Object.entries(artifacts)) {
      if ((await readFile(join(destination, name), "utf8")) !== contents)
        throw new Error(`Generated ${name} differs`);
    }
    console.log(
      "Generated TypeScript operations, models, and schemas match the fresh Go export.",
    );
  } else {
    await mkdir(destination, { recursive: true });
    for (const name of await readdir(destination))
      await rm(join(destination, name), { recursive: true });
    for (const [name, contents] of Object.entries(artifacts))
      await writeFile(join(destination, name), contents);
  }
} finally {
  await rm(temporary, { recursive: true, force: true });
}
