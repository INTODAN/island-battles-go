#!/usr/bin/env python3
"""Generate the SDK's models from the checked-in player OpenAPI document."""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

PROJECT = Path(__file__).resolve().parents[1]
REPOSITORY = PROJECT.parents[1]
ARTIFACT = REPOSITORY / "backend" / "api" / "openapi.json"
GENERATED = PROJECT / "island_battles_client" / "_generated.py"
ENTITIES = "island_battles_client._entities"
# Generated models gain hand-written behavior only through these base classes.
BASE_CLASSES = {
    "Castle": f"{ENTITIES}.BoardEntity",
    "SoldierGroup": f"{ENTITIES}.SoldierGroupBase",
    "Generation": f"{ENTITIES}.GenerationBase",
}
HEADER = (
    "# Generated by scripts/generate.py from backend/api/openapi.json. Do not edit;\n"
    "# change the Go API types, export the document, and regenerate instead."
)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the OpenAPI document or generated models are stale",
    )
    args = parser.parse_args(argv)
    try:
        check_artifact()
        with tempfile.TemporaryDirectory(prefix="island-sdk-") as temporary:
            output = Path(temporary) / "_generated.py"
            generate(output)
            if args.check:
                if (
                    not GENERATED.is_file()
                    or GENERATED.read_bytes() != output.read_bytes()
                ):
                    raise RuntimeError(
                        f"{GENERATED.relative_to(REPOSITORY)} is stale; run scripts/generate.py"
                    )
            else:
                GENERATED.write_bytes(output.read_bytes())
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print(f"generation failed: {error}", file=sys.stderr)
        return 1
    return 0


def check_artifact() -> None:
    environment = os.environ.copy()
    environment.setdefault("GOCACHE", "/tmp/island-battles-go-cache")
    subprocess.run(
        [
            "go",
            "run",
            "./backend/cmd/export-openapi",
            "--output",
            str(ARTIFACT),
            "--check",
        ],
        cwd=REPOSITORY,
        env=environment,
        check=True,
    )


def generate(output: Path) -> None:
    subprocess.run(
        [
            "datamodel-codegen",
            "--input",
            str(ARTIFACT),
            "--input-file-type",
            "openapi",
            "--output",
            str(output),
            "--output-model-type",
            "pydantic_v2.BaseModel",
            "--target-python-version",
            "3.14",
            "--base-class",
            f"{ENTITIES}.GameModel",
            "--base-class-map",
            json.dumps(BASE_CLASSES),
            # Strict scalars reject bools and numeric strings; integers still
            # satisfy float fields.
            "--strict-types",
            "str",
            "int",
            "float",
            "bool",
            "--use-annotated",
            "--field-constraints",
            "--enum-field-as-literal",
            "all",
            "--use-generic-container-types",
            "--use-union-operator",
            # Tolerate fields added by newer servers.
            "--extra-fields",
            "ignore",
            "--use-field-description",
            "--use-double-quotes",
            "--keep-model-order",
            "--disable-timestamp",
            "--custom-file-header",
            HEADER,
            "--formatters",
            "ruff-format",
            "ruff-check",
        ],
        cwd=PROJECT,
        check=True,
    )


if __name__ == "__main__":
    raise SystemExit(main())
