def with_unknown_fields(board: dict) -> dict:
    """Fields a newer server might add; clients must ignore them."""
    extended = copy.deepcopy(board)
    extended["weather"] = "rain"
    extended["castles"][0]["banner"] = "blue"
    extended["clashes"][0]["participants"][0]["note"] = {"nested": True}
    return extended


def mutated(path: list, value: object = None, *, delete: bool = False) -> dict:
    board = copy.deepcopy(BOARD)
    target = board
    for key in path[:-1]:
        target = target[key]
    if delete:
        del target[path[-1]]
    else:
        target[path[-1]] = value
    return board


def valid(name: str, generation: dict, public: dict | None = None) -> dict:
    case = {"name": name, "generation": generation}
    if public is not None:
        case["expected_generation"] = public
    case["expected"] = reference.evaluate(public or generation)
    return case


def build_model_fixtures() -> dict:
    return {
        "description": (
            "Generated by island_conformance/fixtures.py; expected values come from "
            "island_conformance/reference.py. Wire generations for the `evaluate` adapter message. "
            "Entities are castles followed by soldier groups, in wire order. "
            "Numbers compare with a relative tolerance of 1e-9."
        ),
        "valid": [
            valid(
                "utilities across castles, groups, a neutral castle and an arrived group",
                BOARD,
            ),
            valid(
                "unknown fields from newer servers are ignored",
                with_unknown_fields(BOARD),
                BOARD,
            ),
            valid("coincident neutral castles and negative coordinates", COINCIDENT),
            valid(
                "generation without groups or clashes",
                {"id": 1, "castles": [CASTLES[0]], "soldier_groups": [], "clashes": []},
            ),
        ],
        "invalid": [
            {
                "name": "soldier group destination is not in the generation",
                "generation": mutated(
                    ["soldier_groups", 0, "destination_castle_id"], 9
                ),
            },
            {
                "name": "negative castle ID",
                "generation": mutated(["castles", 0, "id"], -1),
            },
            {
                "name": "fractional soldier count",
                "generation": mutated(["castles", 0, "soldiers"], 1.5),
            },
            {
                "name": "boolean soldier count",
                "generation": mutated(["castles", 0, "soldiers"], True),
            },
            {
                "name": "string coordinate",
                "generation": mutated(["castles", 0, "x"], "1"),
            },
            {
                "name": "zero clash radius",
                "generation": mutated(["soldier_groups", 0, "clash_radius"], 0),
            },
            {
                "name": "clash time after the turn",
                "generation": mutated(["clashes", 0, "time"], 1.5),
            },
            {"name": "clash ID zero", "generation": mutated(["clashes", 0, "id"], 0)},
            {"name": "generation ID zero", "generation": mutated(["id"], 0)},
            {"name": "castles are null", "generation": mutated(["castles"], None)},
            {
                "name": "clashes are missing",
                "generation": mutated(["clashes"], delete=True),
            },
            {
                "name": "soldier group misses its origin",
                "generation": mutated(
                    ["soldier_groups", 0, "origin_castle_id"], delete=True
                ),
            },
        ],
    }


def render() -> str:
    return json.dumps(build_model_fixtures(), indent=2) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if fixtures/models.json is stale"
    )
    args = parser.parse_args(argv)
    if args.check:
        if FIXTURES.read_text() != render():
            print(
                f"{FIXTURES} is stale; run python -m island_conformance.fixtures",
                file=sys.stderr,
            )
            return 1
        return 0
    FIXTURES.write_text(render())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
